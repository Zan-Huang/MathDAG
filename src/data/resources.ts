/** Catalog with viewer metadata (embeds, framing flags, parts, corrected URLs) layered on. */
export const resources: Resource[] = catalog.map((resource) => ({
  ...resource,
  ...(embedOverrides[resource.id] ?? {}),
}))

export const resourcesById: Record<string, Resource> = Object.fromEntries(
  resources.map((resource) => [resource.id, resource]),
)

export const resourcesByNode: Record<string, Resource[]> = {}
for (const resource of resources) {
  for (const nodeId of resource.nodeIds) {
    if (!resourcesByNode[nodeId]) resourcesByNode[nodeId] = []
    resourcesByNode[nodeId].push(resource)
  }
}

export function searchResources(query: string): Resource[] {
  const q = query.trim().toLowerCase()
  if (!q) return resources
  return resources.filter((resource) => {
    const hay = `${resource.title} ${resource.authors} ${resource.description} ${resource.type}`.toLowerCase()
    return hay.includes(q)
  })
}
